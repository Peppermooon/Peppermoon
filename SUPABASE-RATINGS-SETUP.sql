-- Run once in the Peppermoon Supabase project's SQL Editor.
begin;
create table if not exists public.pepper_ratings (
 id bigint generated by default as identity primary key,
 slug text not null unique,
 title text not null check (length(title) between 1 and 160),
 category text not null check (category in ('Movies','Gaming','TV Series')),
 release_year integer check (release_year between 1900 and 2100),
 score numeric(3,1) not null check (score between 0 and 10),
 summary text not null default '' check (length(summary)<=400),
 review text not null default '',
 image_url text not null default '',
 status text not null default 'draft' check (status in ('draft','published')),
 top_rank integer check (top_rank between 1 and 10),
 created_by uuid references auth.users(id) default auth.uid(),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 constraint pepper_ratings_published_review check (status <> 'published' or length(trim(review))>=10)
);
create unique index if not exists pepper_ratings_category_rank on public.pepper_ratings(category,top_rank) where top_rank is not null and status='published';
create or replace function public.pepper_ratings_touch_updated_at() returns trigger language plpgsql set search_path=public as $$
begin new.updated_at=now(); return new; end;
$$;
drop trigger if exists pepper_ratings_updated_at on public.pepper_ratings;
create trigger pepper_ratings_updated_at before update on public.pepper_ratings for each row execute function public.pepper_ratings_touch_updated_at();
alter table public.pepper_ratings enable row level security;
grant select on public.pepper_ratings to anon,authenticated;
grant insert,update,delete on public.pepper_ratings to authenticated;
grant usage,select on sequence public.pepper_ratings_id_seq to authenticated;
drop policy if exists pepper_ratings_public_read on public.pepper_ratings;
create policy pepper_ratings_public_read on public.pepper_ratings for select to anon,authenticated using (status='published');
drop policy if exists pepper_ratings_admin on public.pepper_ratings;
create policy pepper_ratings_admin on public.pepper_ratings for all to authenticated
 using (exists(select 1 from public.profiles where id=auth.uid() and role='admin'))
 with check (exists(select 1 from public.profiles where id=auth.uid() and role='admin'));
commit;
